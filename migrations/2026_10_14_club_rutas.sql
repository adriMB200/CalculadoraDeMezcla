CREATE TABLE IF NOT EXISTS public.club_rutas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo VARCHAR(100) NOT NULL CHECK (length(trim(titulo)) >= 4),
  fecha_salida TIMESTAMPTZ NOT NULL,
  zona VARCHAR(100) NOT NULL CHECK (length(trim(zona)) > 0),
  dificultad VARCHAR(10) NOT NULL CHECK (dificultad IN ('facil', 'media', 'alta')),
  kilometros INTEGER CHECK (kilometros BETWEEN 1 AND 1000),
  terreno VARCHAR(140) NOT NULL,
  plazas INTEGER NOT NULL CHECK (plazas BETWEEN 1 AND 100),
  encuentro VARCHAR(300) NOT NULL CHECK (length(trim(encuentro)) >= 4),
  estado VARCHAR(12) NOT NULL DEFAULT 'publicada' CHECK (estado IN ('publicada','cancelada')),
  creador_id INTEGER NOT NULL REFERENCES public.usuarios(id),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS club_rutas_fecha_idx ON public.club_rutas(fecha_salida) WHERE estado = 'publicada';

CREATE TABLE IF NOT EXISTS public.club_inscripciones (
  ruta_id BIGINT NOT NULL REFERENCES public.club_rutas(id) ON DELETE CASCADE,
  usuario_id INTEGER NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  inscrito_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (ruta_id, usuario_id)
);
CREATE INDEX IF NOT EXISTS club_inscripciones_usuario_idx ON public.club_inscripciones(usuario_id);

-- La función serializa las inscripciones por ruta con FOR UPDATE.
-- El conteo se hace DESPUÉS del bloqueo, evitando plazas duplicadas bajo concurrencia.
CREATE OR REPLACE FUNCTION public.club_apuntarse(p_ruta_id BIGINT, p_usuario_id INTEGER)
RETURNS TEXT LANGUAGE plpgsql AS $$
DECLARE v_ruta public.club_rutas%ROWTYPE;
BEGIN
  SELECT * INTO v_ruta FROM public.club_rutas
  WHERE id = p_ruta_id FOR UPDATE;
  IF NOT FOUND OR v_ruta.estado <> 'publicada' OR v_ruta.fecha_salida <= NOW() THEN
    RETURN 'no_disponible';
  END IF;
  IF EXISTS (SELECT 1 FROM public.club_inscripciones
             WHERE ruta_id = p_ruta_id AND usuario_id = p_usuario_id) THEN
    RETURN 'ya_inscrito';
  END IF;
  IF (SELECT COUNT(*) FROM public.club_inscripciones WHERE ruta_id = p_ruta_id) >= v_ruta.plazas THEN
    RETURN 'completa';
  END IF;
  INSERT INTO public.club_inscripciones(ruta_id, usuario_id) VALUES (p_ruta_id, p_usuario_id);
  RETURN 'inscrito';
END;
$$;
COMMIT;
