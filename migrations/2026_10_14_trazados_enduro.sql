BEGIN;
CREATE TABLE IF NOT EXISTS public.club_trazados (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  autor_id INTEGER NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  titulo VARCHAR(100) NOT NULL CHECK (char_length(trim(titulo)) BETWEEN 4 AND 100),
  provincia VARCHAR(70) NOT NULL,
  dificultad VARCHAR(10) NOT NULL CHECK (dificultad IN ('facil','media','alta')),
  descripcion VARCHAR(1000) NOT NULL,
  distancia_km NUMERIC(8,2) NOT NULL CHECK (distancia_km > 0 AND distancia_km <= 500),
  puntos JSONB NOT NULL CHECK (jsonb_typeof(puntos) = 'array' AND jsonb_array_length(puntos) BETWEEN 2 AND 400),
  estado VARCHAR(15) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','publicado','rechazado')),
  acceso VARCHAR(15) NOT NULL DEFAULT 'privado' CHECK (acceso IN ('privado','publico','inscritos')),
  salida_id BIGINT REFERENCES public.club_rutas(id) ON DELETE SET NULL,
  wikiloc_url TEXT,
  revisado_por INTEGER REFERENCES public.usuarios(id) ON DELETE SET NULL,
  revisado_en TIMESTAMPTZ,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT ruta_inscritos_salida CHECK (acceso <> 'inscritos' OR salida_id IS NOT NULL),
  CONSTRAINT ruta_estado_acceso CHECK (estado = 'publicado' OR acceso = 'privado')
);
CREATE INDEX IF NOT EXISTS club_trazados_estado_idx ON public.club_trazados (estado, creado_en DESC);
CREATE INDEX IF NOT EXISTS club_trazados_autor_idx ON public.club_trazados (autor_id, creado_en DESC);
CREATE INDEX IF NOT EXISTS club_trazados_salida_idx ON public.club_trazados (salida_id);
COMMIT;
