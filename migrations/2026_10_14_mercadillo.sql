-- Aplicar DESPUÉS de las migraciones anteriores. Revisar previamente con una rama de Neon.
BEGIN;
CREATE TABLE IF NOT EXISTS public.merc_anuncios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vendedor_id INTEGER NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
 titulo VARCHAR(100) NOT NULL CHECK(length(trim(titulo)) >= 8),
 descripcion VARCHAR(1000) NOT NULL CHECK(length(trim(descripcion)) >= 20),
 categoria VARCHAR(20) NOT NULL CHECK(categoria IN ('motos','recambios','equipacion','herramientas','otros')),
 condicion VARCHAR(10) NOT NULL CHECK(condicion IN ('nuevo','usado')),
 precio_centimos INTEGER NOT NULL CHECK(precio_centimos BETWEEN 0 AND 10000000),
 zona VARCHAR(70) NOT NULL CHECK(length(trim(zona)) >= 2),
 estado VARCHAR(12) NOT NULL DEFAULT 'pendiente'
   CHECK(estado IN ('pendiente','activo','rechazado','vendido','retirado')),
 motivo_revision VARCHAR(250),
 moderado_por INTEGER REFERENCES public.usuarios(id) ON DELETE SET NULL,
 creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
 actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
 moderado_en TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS merc_publicos_idx ON public.merc_anuncios(creado_en DESC,id DESC) WHERE estado='activo';
CREATE INDEX IF NOT EXISTS merc_vendedor_idx ON public.merc_anuncios(vendedor_id,creado_en DESC);
CREATE INDEX IF NOT EXISTS merc_revision_idx ON public.merc_anuncios(creado_en ASC) WHERE estado='pendiente';

CREATE TABLE IF NOT EXISTS public.merc_mensajes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 anuncio_id BIGINT NOT NULL REFERENCES public.merc_anuncios(id) ON DELETE CASCADE,
 remitente_id INTEGER NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
 destinatario_id INTEGER NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
 cuerpo VARCHAR(1000) NOT NULL CHECK(length(trim(cuerpo)) BETWEEN 5 AND 1000),
 creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(remitente_id <> destinatario_id)
);
CREATE INDEX IF NOT EXISTS merc_mensajes_remitente_idx ON public.merc_mensajes(remitente_id,creado_en DESC);
CREATE INDEX IF NOT EXISTS merc_mensajes_destinatario_idx ON public.merc_mensajes(destinatario_id,creado_en DESC);
CREATE INDEX IF NOT EXISTS merc_mensajes_conversacion_idx ON public.merc_mensajes(anuncio_id,creado_en ASC);

CREATE TABLE IF NOT EXISTS public.merc_reportes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 anuncio_id BIGINT NOT NULL REFERENCES public.merc_anuncios(id) ON DELETE CASCADE,
 usuario_id INTEGER REFERENCES public.usuarios(id) ON DELETE SET NULL,
 motivo VARCHAR(500) NOT NULL CHECK(length(trim(motivo)) BETWEEN 15 AND 500),
 estado VARCHAR(12) NOT NULL DEFAULT 'pendiente' CHECK(estado IN ('pendiente','revisado')),
 creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
 revisado_en TIMESTAMPTZ,
 revisor_id INTEGER REFERENCES public.usuarios(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS merc_reportes_revision_idx ON public.merc_reportes(creado_en ASC) WHERE estado='pendiente';
COMMIT;
