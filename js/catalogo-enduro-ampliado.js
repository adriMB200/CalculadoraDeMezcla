export function integrarCatalogoExistente(catalogo) {
  for (const item of MODELOS_AMPLIACION) {
    const recurso = {
      tipo: 'Información del fabricante',
      titulo: `Gama oficial ${item.anio} · comprueba variante y año`,
      enlace: item.fuente,
      anios: [item.anio],
      origen: 'Fabricante · índice de gama, NO manual de taller'
    };
    let moto = catalogo.find(m => m.marca.toUpperCase() === item.marca && m.modelo.toUpperCase() === item.modelo.toUpperCase());
    if (!moto) {
      moto = {
        id: `${item.marca.toLowerCase()}-${item.modelo.toLowerCase().replace(/[^a-z0-9]+/g,'-')}`,
        marca: item.marca, modelo: item.modelo, anios: [], recursos: [],
        aclaracion: 'Modelo identificado en la gama oficial. Todavía no hay manual ni tabla de pares específicos publicados en Enduro Nalón para este año.',
        fichasPorAnio: {}
      };
      catalogo.push(moto);
    }
    if (!moto.anios.includes(item.anio)) moto.anios.push(item.anio);
    if (!moto.recursos.some(r => r.tipo === recurso.tipo && r.anios.includes(item.anio) && r.enlace === recurso.enlace)) moto.recursos.push(recurso);
    moto.fichasPorAnio ||= {};
    moto.fichasPorAnio[item.anio] = {
      motor: item.motor, cilindradaClase: item.cilindradaClase,
      nota: 'Categoría comercial indicada por el fabricante; no se dispone de pares de apriete ni manual exacto en la web para este año.'
    };
    moto.anios.sort((a,b)=>a-b);
  }
  return catalogo;
}
